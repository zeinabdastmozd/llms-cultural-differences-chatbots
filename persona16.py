def generate_reply(tokenizer, model, prompt, temperature):
    print("\n--- Generating Reply ---")
    print(f"Temperature: {temperature}")
    inputs = tokenizer(prompt, return_tensors="pt").to(model.device)
    gen_cfg = GenerationConfig(
        temperature=temperature,
        top_p=0.9,
        do_sample=True,
        max_new_tokens=30
    )
    outputs = model.generate(**inputs, generation_config=gen_cfg, pad_token_id=tokenizer.eos_token_id)
    text = tokenizer.decode(outputs[0], skip_special_tokens=True)

    raw_reply = text.split(f"{prompt.splitlines()[-1]}")[-1].strip()
    print(f"\n[RAW REPLY]: {raw_reply}")

    cleaned_reply = clean_text(raw_reply)
    final_reply = clean_to_full_sentence(cleaned_reply)

    print(f"[CLEANED REPLY]: {cleaned_reply}")
    print(f"[FINAL REPLY]: {final_reply}")

    return final_reply


