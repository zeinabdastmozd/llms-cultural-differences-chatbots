def format_prompt(current_speaker, other_character, identity, topic, convo_history, prompt_suffix):
    system = (
        f"You are a {identity} {current_speaker.lower()} conversing with your "
        f"{identity} {other_character.lower()} about {topic.lower()}. "
        f"Speak in a tone and manner typical for that role and cultural context. "
        f"{prompt_suffix}\n"
    )
    chat = "\n".join(convo_history) if convo_history else ""
    prompt = system + chat + f"\n[{current_speaker.upper()}]:"
    print("\n--- Prompt Built ---")
    print(prompt)
    return prompt


